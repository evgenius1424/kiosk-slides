import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { parseArgs } from 'node:util'
import { build } from 'esbuild'
import { chromium } from '@playwright/test'

const SIZE = 400
const GLYPHS = [
  ...Array.from({ length: 94 }, (_, i) => String.fromCharCode(33 + i)),
  ...Array.from({ length: 64 }, (_, i) => String.fromCharCode(0x410 + i)),
  ...'ЁёЙйÀÁÂÃÄÅÇÈÉÊËÌÍÎÏÑÒÓÔÕÖÙÚÛÜÝàáâãäåçèéêëìíîïñòóôõöùúûüýÿ“”‘’«»—–…№€😀',
]
const BODY = /^[A-Za-z0-9А-ИК-ик-я()[\]{}]$/
const SHAPED = /^[\p{L}\p{N}()[\]«»“”%&?!]$/u
const EMOJI = '😀'
const OUT = 'lib/presentation/pill-fonts.ts'

const { values } = parseArgs({
  options: {
    remeasure: { type: 'boolean', default: false },
    out: { type: 'string', default: OUT },
    pad: { type: 'string', default: '0.18' },
    edge: { type: 'string', default: '0.03' },
  },
})
const PAD = Number(values.pad)
const EDGE = Number(values.edge)
const cache = path.resolve('.theme-lab')
await mkdir(cache, { recursive: true })
const bundle = path.join(cache, 'pill-metrics.mjs')
await build({
  stdin: {
    contents: "export { fonts, fontFace } from './lib/presentation/look'",
    resolveDir: process.cwd(),
    loader: 'ts',
  },
  outfile: bundle,
  bundle: true,
  platform: 'node',
  format: 'esm',
  logLevel: 'warning',
  plugins: [
    {
      name: 'without-pill-metrics',
      setup: build =>
        build.onLoad({ filter: /pill-fonts\.ts$/ }, () => ({
          contents:
            'export const PILL_PAD = 0, PILL_GLYPHS = [], PILL_EMOJI = 0, PILL_TALL = "", pillFonts = { classic: { top: 0, bottom: 0, tallTop: 0, tallBottom: 0 } }',
          loader: 'js',
        })),
    },
  ],
})
const { fonts, fontFace } = await import(bundle)
const shapes = await loadShapes()

const tallGlyphs = new Set()
const measured = shapes.map(({ id, ascent, descent, upright, italic }) => {
  const extent = (glyphs, test) =>
    glyphs.filter(g => test(g.glyph)).flatMap(g => g.rows.map(([y]) => y))
  const body = extent(upright, g => BODY.test(g))
  const tall = extent([...upright, ...italic], () => true)
  const top = most(body)
  const bottom = -least(body)
  for (const g of upright)
    if (g.rows.some(([y]) => y > top + 0.01 || y < -bottom - 0.01)) tallGlyphs.add(g.glyph)
  const radius = Math.min(
    (top + bottom) / 2 + PAD,
    ...[...upright, ...italic]
      .filter(g => SHAPED.test(g.glyph) && g.rows.every(([y]) => y <= top && y >= -bottom))
      .map(g => largestRadius(g, top, bottom)),
  )
  return {
    id,
    ascent,
    descent,
    top: round(top + PAD),
    bottom: round(bottom + PAD),
    tallTop: round(most(tall) + PAD),
    tallBottom: round(Math.max(bottom, -least(tall)) + PAD),
    radius: round(radius),
    starts: upright.map(g => edges(g).start),
    ends: upright.map(g => edges(g).end),
    italicStarts: italic.map(g => edges(g).start),
    italicEnds: italic.map(g => edges(g).end),
  }
})

const list = values => `[${values.join(', ')}]`
const entries = measured.map(
  m =>
    `  '${m.id}': {\n    ascent: ${m.ascent},\n    descent: ${m.descent},\n    top: ${m.top},\n    bottom: ${m.bottom},\n    tallTop: ${m.tallTop},\n    tallBottom: ${m.tallBottom},\n    radius: ${m.radius},\n    starts: ${list(m.starts)},\n    ends: ${list(m.ends)},\n    italicStarts: ${list(m.italicStarts)},\n    italicEnds: ${list(m.italicEnds)},\n  },`,
)
await writeFile(
  values.out,
  `// Generated by scripts/pill-metrics.mjs from the fonts at weight 800: pad ${PAD}, edge ${EDGE}.\n\nexport const PILL_PAD = ${PAD}\n\nexport const PILL_GLYPHS = ${JSON.stringify(GLYPHS)}\n\nexport const PILL_EMOJI = PILL_GLYPHS.indexOf('${EMOJI}')\n\nexport const PILL_TALL = ${JSON.stringify([...tallGlyphs].join(''))}\n\nexport const pillFonts: Record<string, PillFont> = {\n${entries.join('\n')}\n}\n\ntype PillFont = {\n  ascent: number\n  descent: number\n  top: number\n  bottom: number\n  tallTop: number\n  tallBottom: number\n  radius: number\n  starts: number[]\n  ends: number[]\n  italicStarts: number[]\n  italicEnds: number[]\n}\n`,
)
console.log(`Wrote ${values.out}`)

function edges(glyph) {
  if (!glyph.rows.length) return { start: 0, end: 0 }
  return {
    start: round(-Math.min(...glyph.rows.map(([, left]) => left))),
    end: round(Math.max(...glyph.rows.map(([, , right]) => right)) - glyph.advance),
  }
}

function largestRadius(glyph, top, bottom) {
  const left = Math.min(...glyph.rows.map(([, l]) => l))
  const right = Math.max(...glyph.rows.map(([, , r]) => r))
  const fits = radius =>
    glyph.rows.every(([y, l, r]) =>
      [PAD + l - left, PAD + right - r].every(across => {
        const down = Math.min(top + PAD - y, y + bottom + PAD)
        return (
          across >= radius ||
          down >= radius ||
          Math.hypot(radius - across, radius - down) <= radius - EDGE
        )
      }),
    )
  let low = 0
  let high = (top + bottom) / 2 + PAD
  for (let i = 0; i < 30; i++) {
    const mid = (low + high) / 2
    if (fits(mid)) low = mid
    else high = mid
  }
  return low
}

async function loadShapes() {
  const file = path.join(cache, 'pill-shapes.json')
  if (!values.remeasure)
    try {
      return JSON.parse(await readFile(file, 'utf8'))
    } catch {}
  const faces = []
  for (const font of fonts)
    for (const fontFile of font.files) {
      const data = await readFile(path.join('public/fonts', fontFile.file))
      faces.push(fontFace(fontFile, `data:font/woff2;base64,${data.toString('base64')}`))
    }
  const browser = await chromium.launch(
    process.env.CHROMIUM ? { executablePath: process.env.CHROMIUM } : {},
  )
  const page = await browser.newPage()
  await page.setContent(
    `<style>${faces.join('')}</style>${fonts
      .flatMap(f =>
        ['normal', 'italic'].map(
          style => `<p style="font:${style} 800 20px ${f.stack}">${GLYPHS.join('')}</p>`,
        ),
      )
      .join('')}`,
  )
  await page.evaluate(() => document.fonts.ready)
  const result = await page.evaluate(measure, {
    fonts: fonts.map(f => ({ id: f.id, stack: f.stack })),
    glyphs: GLYPHS,
    size: SIZE,
  })
  await browser.close()
  await writeFile(file, JSON.stringify(result))
  return result
}

function measure({ fonts, glyphs, size }) {
  const canvas = document.createElement('canvas')
  canvas.width = size * 3
  canvas.height = size * 3
  const context = canvas.getContext('2d', { willReadFrequently: true })
  const originX = size
  const baseline = size * 2
  const shapes = (style, stack) =>
    glyphs.map(glyph => {
      context.font = `${style} 800 ${size}px ${stack}`
      context.clearRect(0, 0, canvas.width, canvas.height)
      context.fillText(glyph, originX, baseline)
      const { data } = context.getImageData(0, 0, canvas.width, canvas.height)
      const rows = []
      for (let y = 0; y < canvas.height; y++) {
        let left = -1
        let right = -1
        for (let x = 0; x < canvas.width; x++)
          if (data[(y * canvas.width + x) * 4 + 3] >= 128) {
            if (left < 0) left = x
            right = x + 1
          }
        if (left >= 0)
          rows.push([
            (baseline - y - 0.5) / size,
            (left - originX) / size,
            (right - originX) / size,
          ])
      }
      return { glyph, advance: context.measureText(glyph).width / size, rows }
    })
  return fonts.map(({ id, stack }) => {
    context.font = `800 ${size}px ${stack}`
    const metrics = context.measureText('H')
    return {
      id,
      ascent: Math.round((metrics.fontBoundingBoxAscent / size) * 1000) / 1000,
      descent: Math.round((metrics.fontBoundingBoxDescent / size) * 1000) / 1000,
      upright: shapes('normal', stack),
      italic: shapes('italic', stack),
    }
  })
}

function most(values) {
  return values.reduce((a, b) => Math.max(a, b), -Infinity)
}

function least(values) {
  return values.reduce((a, b) => Math.min(a, b), Infinity)
}

function round(value) {
  return Math.round(value * 1000) / 1000
}
